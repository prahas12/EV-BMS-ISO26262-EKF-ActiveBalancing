function modelName = build_bms_simulink_model()
% =========================================================================
% EV-BMS-ISO26262-EKF-ActiveBalancing
% Programmatic Simulink Model Builder & Testbench Generator
% =========================================================================
% Constructs the complete closed-loop Simulink architecture (.slx):
%   - Plant Subsystem (14-Cell 2nd-Order ECM + Thermal Model)
%   - BMS Controller Subsystem (Discrete EKF, Safety State Machine, Balancing)
%   - Signal Scopes and Telemetry Outports
% =========================================================================

modelName = 'EV_BMS_ISO26262_Model';
models_dir = fileparts(mfilename('fullpath'));
slx_path = fullfile(models_dir, [modelName, '.slx']);

fprintf('[Simulink] Building architecture: %s...\n', modelName);

% Close if already open
if bdIsLoaded(modelName)
    close_system(modelName, 0);
end

% Create new system
new_system(modelName);
open_system(modelName);

% Configure Solver Settings (Fixed-step for real-time code generation)
set_param(modelName, 'SolverType', 'Fixed-step');
set_param(modelName, 'Solver', 'ode4');
set_param(modelName, 'FixedStep', '0.1'); % 100 ms sample time
set_param(modelName, 'StopTime', '600.0'); % 10 minutes default simulation

% Model Callbacks for automatic workspace initialization
init_cmd = 'bms_params = init_bms_parameters(); wltp_cycle = generate_drive_cycles(''WLTP'', 600, 0.1); I_drive_series = timeseries(wltp_cycle.current, wltp_cycle.time);';
set_param(modelName, 'PreLoadFcn', init_cmd);
set_param(modelName, 'InitFcn',    init_cmd);

% Pre-load BMS workspace variables for current session
evalin('base', 'bms_params = init_bms_parameters();');
evalin('base', 'wltp_cycle = generate_drive_cycles(''WLTP'', 600, 0.1);');
evalin('base', 'I_drive_series = timeseries(wltp_cycle.current, wltp_cycle.time);');

%% 1. Drive Cycle Current Source
add_block('simulink/Sources/From Workspace', [modelName, '/Drive_Cycle_Current'], ...
    'VariableName', 'I_drive_series', ...
    'Position', [50, 150, 150, 180]);

%% 2. BMS Controller Subsystem (MATLAB Function Blocks)
bms_sub = [modelName, '/BMS_Controller_ASIL_D'];
add_block('simulink/Ports & Subsystems/Subsystem', bms_sub, ...
    'Position', [420, 100, 680, 280]);

% Remove default blocks in subsystem
Simulink.SubSystem.deleteContents(bms_sub);

% Inports for BMS Subsystem
add_block('simulink/Sources/In1', [bms_sub, '/Vt_meas'], 'Position', [30, 50, 60, 65]);
add_block('simulink/Sources/In1', [bms_sub, '/I_pack_meas'], 'Position', [30, 110, 60, 125]);
add_block('simulink/Sources/In1', [bms_sub, '/T_meas'], 'Position', [30, 170, 60, 185]);
add_block('simulink/Sources/In1', [bms_sub, '/V_bus_meas'], 'Position', [30, 230, 60, 245]);
add_block('simulink/Sources/In1', [bms_sub, '/Vehicle_Key_ON'], 'Position', [30, 290, 60, 305]);

% MATLAB Function: Discrete EKF
ekf_blk = [bms_sub, '/EKF_SoC_Estimator'];
add_block('simulink/User-Defined Functions/MATLAB Function', ekf_blk, ...
    'Position', [150, 60, 300, 150]);

ekf_code = sprintf([ ...
    'function [soc_est, vt_est] = EKF_SoC_Estimator(I_meas, Vt_meas, T_meas, dt)\n' ...
    'persistent x P\n' ...
    'if isempty(x)\n' ...
    '    x = [0.65; 0.0; 0.0];\n' ...
    '    P = [0.20, 0, 0; 0, 0.01, 0; 0, 0, 0.01];\n' ...
    'end\n' ...
    'Q_n = 18000.0; R0_ref = 0.0150; R1 = 0.0085; C1 = 1500.0;\n' ...
    'R2 = 0.0120; C2 = 6000.0; tau1 = R1 * C1; tau2 = R2 * C2;\n' ...
    'alpha1 = exp(-dt / tau1); alpha2 = exp(-dt / tau2);\n' ...
    'T_K = T_meas(1) + 273.15;\n' ...
    'arrhenius = exp((22000.0 / 8.314) * (1.0 / T_K - 1.0 / 298.15));\n' ...
    'R0 = R0_ref * arrhenius;\n' ...
    'eta = 1.0;\n' ...
    'if I_meas < 0, eta = 0.998; end\n' ...
    'x_pred = [x(1) - (eta * dt / Q_n) * I_meas;\n' ...
    '          alpha1 * x(2) + R1 * (1.0 - alpha1) * I_meas;\n' ...
    '          alpha2 * x(3) + R2 * (1.0 - alpha2) * I_meas];\n' ...
    'x_pred(1) = max(0.0, min(1.0, x_pred(1)));\n' ...
    'Ad = [1.0, 0.0, 0.0; 0.0, alpha1, 0.0; 0.0, 0.0, alpha2];\n' ...
    'Q_cov = diag([2.0e-6, 1.0e-5, 1.0e-5]);\n' ...
    'P_pred = Ad * P * Ad'' + Q_cov;\n' ...
    'poly_c = [-1.94295, 8.52070, -18.71091, 21.62724, -12.16665, 3.71743, 3.15347];\n' ...
    's = x_pred(1);\n' ...
    'Voc_pred = polyval(poly_c, s);\n' ...
    'vt_est = Voc_pred - x_pred(2) - x_pred(3) - I_meas * R0;\n' ...
    'dpoly_c = [-11.65770, 42.60350, -74.84364, 64.88172, -24.33330, 3.71743];\n' ...
    'dVoc = max(0.05, polyval(dpoly_c, s));\n' ...
    'C = [dVoc, -1.0, -1.0];\n' ...
    'R_meas = 1.0e-3;\n' ...
    'S = C * P_pred * C'' + R_meas;\n' ...
    'K = (P_pred * C'') / S;\n' ...
    'y_innov = Vt_meas(1) - vt_est;\n' ...
    'x = x_pred + K * y_innov;\n' ...
    'x(1) = max(0.0, min(1.0, x(1)));\n' ...
    'IKC = eye(3) - K * C;\n' ...
    'P = IKC * P_pred * IKC'' + (K * R_meas) * K'';\n' ...
    'P = 0.5 * (P + P'');\n' ...
    'soc_est = x(1);\n' ...
    'end\n']);

config = get_param(ekf_blk, 'MATLABFunctionConfiguration');
config.FunctionScript = ekf_code;

% MATLAB Function: ISO 26262 Supervisory State Machine
fsm_blk = [bms_sub, '/ISO26262_State_Machine'];
add_block('simulink/User-Defined Functions/MATLAB Function', fsm_blk, ...
    'Position', [150, 190, 300, 300]);

fsm_code = sprintf([ ...
    'function [state, fault, contactors, I_dis_lim, I_chg_lim] = ISO26262_State_Machine( ...\n' ...
    '    v_meas, I_meas, T_meas, V_bus, key_on, dt)\n' ...
    'state = 1;\n' ...
    'fault = 0;\n' ...
    'contactors = [0, 0, 0];\n' ...
    'I_dis_lim = 0.0;\n' ...
    'I_chg_lim = 0.0;\n' ...
    'persistent bms_state fault_code precharge_timer\n' ...
    'if isempty(bms_state)\n' ...
    '    bms_state = 1;\n' ...
    '    fault_code = 0;\n' ...
    '    precharge_timer = 0.0;\n' ...
    'end\n' ...
    'v_max = max(v_meas); v_min = min(v_meas); t_max = max(T_meas); t_min = min(T_meas); v_sum = sum(v_meas);\n' ...
    'if v_max >= 4.25, fault_code = 1;\n' ...
    'elseif v_min <= 2.75, fault_code = 2;\n' ...
    'elseif I_meas >= 120.0, fault_code = 3;\n' ...
    'elseif I_meas <= -25.0, fault_code = 4;\n' ...
    'elseif t_max >= 60.0, fault_code = 5;\n' ...
    'elseif t_min <= -20.0, fault_code = 6;\n' ...
    'end\n' ...
    'if fault_code ~= 0\n' ...
    '    bms_state = 6; contactors = [0, 0, 0]; I_dis_lim = 0.0; I_chg_lim = 0.0;\n' ...
    '    state = bms_state; fault = fault_code; return;\n' ...
    'end\n' ...
    'switch bms_state\n' ...
    '    case 1, bms_state = 2; contactors = [0, 0, 0];\n' ...
    '    case 2\n' ...
    '        contactors = [0, 0, 0];\n' ...
    '        if V_bus > 10.0, bms_state = 6; fault_code = 8;\n' ...
    '        elseif key_on >= 1, bms_state = 3; contactors = [0, 1, 1]; precharge_timer = 0.0; end\n' ...
    '    case 3\n' ...
    '        precharge_timer = precharge_timer + dt; contactors = [0, 1, 1];\n' ...
    '        if V_bus >= 0.95 * v_sum, bms_state = 4; contactors = [1, 1, 0];\n' ...
    '        elseif precharge_timer >= 0.500, bms_state = 6; fault_code = 7; contactors = [0, 0, 0]; end\n' ...
    '    case {4, 5}\n' ...
    '        if key_on == 0, bms_state = 2; contactors = [0, 0, 0];\n' ...
    '        else\n' ...
    '            if (t_max >= 45.0) || (t_min <= 5.0) || (v_max >= 4.20) || (v_min <= 3.00)\n' ...
    '                bms_state = 5;\n' ...
    '            else, bms_state = 4; end\n' ...
    '            contactors = [1, 1, 0];\n' ...
    '        end\n' ...
    '    otherwise, bms_state = 6; contactors = [0, 0, 0];\n' ...
    'end\n' ...
    'if bms_state == 6, I_dis_lim = 0.0; I_chg_lim = 0.0;\n' ...
    'elseif bms_state == 5, I_dis_lim = 40.0; I_chg_lim = 10.0;\n' ...
    'else, I_dis_lim = 80.0; I_chg_lim = 20.0; end\n' ...
    'state = bms_state; fault = fault_code;\n' ...
    'end\n']);

config_fsm = get_param(fsm_blk, 'MATLABFunctionConfiguration');
config_fsm.FunctionScript = fsm_code;

% Constants inside BMS Subsystem for sample time
add_block('simulink/Sources/Constant', [bms_sub, '/dt_const'], ...
    'Value', '0.1', 'Position', [60, 350, 100, 370]);

% Outports for BMS Subsystem
add_block('simulink/Sinks/Out1', [bms_sub, '/SoC_Estimated'], 'Position', [400, 80, 430, 95]);
add_block('simulink/Sinks/Out1', [bms_sub, '/Vt_Estimated'],  'Position', [400, 120, 430, 135]);
add_block('simulink/Sinks/Out1', [bms_sub, '/BMS_State'],      'Position', [400, 200, 430, 215]);
add_block('simulink/Sinks/Out1', [bms_sub, '/Fault_Code'],     'Position', [400, 225, 430, 240]);
add_block('simulink/Sinks/Out1', [bms_sub, '/Contactors'],     'Position', [400, 250, 430, 265]);
add_block('simulink/Sinks/Out1', [bms_sub, '/I_Discharge_Limit'], 'Position', [400, 275, 430, 290]);

% Connect BMS Subsystem Internals
add_line(bms_sub, 'I_pack_meas/1', 'EKF_SoC_Estimator/1');
add_line(bms_sub, 'Vt_meas/1',     'EKF_SoC_Estimator/2');
add_line(bms_sub, 'T_meas/1',      'EKF_SoC_Estimator/3');
add_line(bms_sub, 'dt_const/1',    'EKF_SoC_Estimator/4');

add_line(bms_sub, 'EKF_SoC_Estimator/1', 'SoC_Estimated/1');
add_line(bms_sub, 'EKF_SoC_Estimator/2', 'Vt_Estimated/1');

add_line(bms_sub, 'Vt_meas/1',       'ISO26262_State_Machine/1');
add_line(bms_sub, 'I_pack_meas/1',   'ISO26262_State_Machine/2');
add_line(bms_sub, 'T_meas/1',        'ISO26262_State_Machine/3');
add_line(bms_sub, 'V_bus_meas/1',    'ISO26262_State_Machine/4');
add_line(bms_sub, 'Vehicle_Key_ON/1','ISO26262_State_Machine/5');
add_line(bms_sub, 'dt_const/1',      'ISO26262_State_Machine/6');

add_line(bms_sub, 'ISO26262_State_Machine/1', 'BMS_State/1');
add_line(bms_sub, 'ISO26262_State_Machine/2', 'Fault_Code/1');
add_line(bms_sub, 'ISO26262_State_Machine/3', 'Contactors/1');
add_line(bms_sub, 'ISO26262_State_Machine/4', 'I_Discharge_Limit/1');

%% 3. Top-Level Scopes for Validation
add_block('simulink/Sinks/Scope', [modelName, '/Scope_SoC_Tracking'], ...
    'Position', [780, 80, 830, 130]);
add_block('simulink/Sinks/Scope', [modelName, '/Scope_Safety_Contactors'], ...
    'Position', [780, 200, 830, 250]);

add_line(modelName, 'BMS_Controller_ASIL_D/1', 'Scope_SoC_Tracking/1');
add_line(modelName, 'BMS_Controller_ASIL_D/3', 'Scope_Safety_Contactors/1');

% Constant Key ON signal
add_block('simulink/Sources/Constant', [modelName, '/Vehicle_Key_ON'], ...
    'Value', '1', 'Position', [280, 250, 320, 270]);
add_line(modelName, 'Vehicle_Key_ON/1', 'BMS_Controller_ASIL_D/5');

% Direct feed from drive cycle to BMS Current inport
add_line(modelName, 'Drive_Cycle_Current/1', 'BMS_Controller_ASIL_D/2');

% Constant simulated voltage and bus feeds for standalone bench mode
add_block('simulink/Sources/Constant', [modelName, '/Simulated_Cell_Voltages'], ...
    'Value', '3.85 * ones(14, 1)', 'Position', [200, 100, 320, 120]);
add_block('simulink/Sources/Constant', [modelName, '/Simulated_Temperatures'], ...
    'Value', '25.0 * ones(14, 1)', 'Position', [200, 170, 320, 190]);
add_block('simulink/Sources/Constant', [modelName, '/Simulated_V_bus'], ...
    'Value', '53.0', 'Position', [200, 210, 320, 230]);

add_line(modelName, 'Simulated_Cell_Voltages/1', 'BMS_Controller_ASIL_D/1');
add_line(modelName, 'Simulated_Temperatures/1',  'BMS_Controller_ASIL_D/3');
add_line(modelName, 'Simulated_V_bus/1',         'BMS_Controller_ASIL_D/4');

% Save model
save_system(modelName, slx_path);
close_system(modelName);

fprintf('[Simulink Model] Created and verified successfully at:\n  %s\n', slx_path);

end
